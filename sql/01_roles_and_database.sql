-- Demo database and least-privilege roles for CoCo for Excel / Google Sheets (Preview).
-- Run as ACCOUNTADMIN (or a role with CREATE DATABASE and CREATE ROLE).

CREATE DATABASE IF NOT EXISTS COCO_SHEETS_DEMO
  COMMENT = 'Snowflake CoCo for Excel and Google Sheets enablement demo';
CREATE SCHEMA IF NOT EXISTS COCO_SHEETS_DEMO.SALES;
CREATE SCHEMA IF NOT EXISTS COCO_SHEETS_DEMO.GOVERNANCE;

CREATE ROLE IF NOT EXISTS COCO_SHEETS_ANALYST
  COMMENT = 'Least-privilege role for CoCo for Excel/Sheets end users';
CREATE ROLE IF NOT EXISTS COCO_SHEETS_STEWARD
  COMMENT = 'Owns demo data, policies, and semantic view';

GRANT USAGE ON DATABASE COCO_SHEETS_DEMO TO ROLE COCO_SHEETS_ANALYST;
GRANT USAGE ON SCHEMA COCO_SHEETS_DEMO.SALES TO ROLE COCO_SHEETS_ANALYST;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE COCO_SHEETS_ANALYST;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE COCO_SHEETS_ANALYST;

GRANT ALL PRIVILEGES ON DATABASE COCO_SHEETS_DEMO TO ROLE COCO_SHEETS_STEWARD;

GRANT ROLE COCO_SHEETS_ANALYST TO ROLE SYSADMIN;
GRANT ROLE COCO_SHEETS_STEWARD TO ROLE SYSADMIN;
