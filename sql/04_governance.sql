-- Masking and row access policies. Users see governed data in the sheet because
-- CoCo queries run under the signed-in user's role.

CREATE OR REPLACE MASKING POLICY COCO_SHEETS_DEMO.GOVERNANCE.MASK_EMAIL
  AS (VAL VARCHAR) RETURNS VARCHAR ->
  CASE WHEN CURRENT_ROLE() IN ('COCO_SHEETS_STEWARD', 'ACCOUNTADMIN') THEN VAL
       ELSE '***MASKED***' END;

CREATE OR REPLACE ROW ACCESS POLICY COCO_SHEETS_DEMO.GOVERNANCE.RAP_REGION
  AS (REGION_VAL VARCHAR) RETURNS BOOLEAN ->
  CURRENT_ROLE() = 'ACCOUNTADMIN'
  OR EXISTS (
    SELECT 1
    FROM COCO_SHEETS_DEMO.GOVERNANCE.REGION_ACCESS R
    WHERE R.ROLE_NAME = CURRENT_ROLE()
      AND R.REGION = REGION_VAL
  );

ALTER TABLE COCO_SHEETS_DEMO.SALES.ORDERS
  MODIFY COLUMN CUSTOMER_EMAIL SET MASKING POLICY COCO_SHEETS_DEMO.GOVERNANCE.MASK_EMAIL;

ALTER TABLE COCO_SHEETS_DEMO.SALES.ORDERS
  ADD ROW ACCESS POLICY COCO_SHEETS_DEMO.GOVERNANCE.RAP_REGION ON (REGION);

GRANT SELECT ON TABLE COCO_SHEETS_DEMO.SALES.ORDERS TO ROLE COCO_SHEETS_ANALYST;
GRANT SELECT ON TABLE COCO_SHEETS_DEMO.GOVERNANCE.REGION_ACCESS TO ROLE COCO_SHEETS_STEWARD;
