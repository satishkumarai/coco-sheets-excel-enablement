-- CoCo for Excel / Sheets usage. ACCOUNT_USAGE views have latency (typically hours).
-- Verified columns: USER_NAME, USAGE_TIME, TOKEN_CREDITS, TOKENS, CREDITS_GRANULAR.

-- Daily token credits by user over the last 30 days.
SELECT
  DATE_TRUNC('DAY', USAGE_TIME) AS USAGE_DAY,
  USER_NAME,
  SUM(TOKEN_CREDITS) AS TOKEN_CREDITS,
  SUM(TOKENS) AS TOKENS
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_CODE_CLI_USAGE_HISTORY
WHERE USAGE_TIME >= DATEADD(DAY, -30, CURRENT_TIMESTAMP())
GROUP BY 1, 2
ORDER BY 1 DESC, 3 DESC;

-- Top users by spend in the last 7 days, to tune per-user credit limits.
SELECT
  USER_NAME,
  SUM(TOKEN_CREDITS) AS TOKEN_CREDITS_7D
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_CODE_CLI_USAGE_HISTORY
WHERE USAGE_TIME >= DATEADD(DAY, -7, CURRENT_TIMESTAMP())
GROUP BY 1
ORDER BY 2 DESC
LIMIT 20;
